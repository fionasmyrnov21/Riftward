#!/usr/bin/env python3
"""Generate pure Kotlin catalog from the shared, authored JSON. No Android/Unity runtime required."""
from pathlib import Path
import json,sys
root=Path(__file__).resolve().parents[1]
source=Path(sys.argv[sys.argv.index('--validate')+1]) if '--validate' in sys.argv else root/'app/src/main/assets/content/catalog.json'
catalog=json.loads(source.read_text())
counts=dict(weapons=6,mods=12,enemies=9,artifacts=8,events=12,echoes=18,rooms=18,roles=4,supplies=6)
ids=set()
for group,count in counts.items():
 if len(catalog[group])!=count:raise SystemExit('Wrong count: '+group)
 for row in catalog[group]:
  if row['id'] in ids:raise SystemExit('Duplicate ID: '+row['id'])
  ids.add(row['id'])
for w in catalog['weapons']:
 if not(w['damage']>0 and w['range']>0 and w['ammo']>0 and 0<=w['unlock']<=3):raise SystemExit('Invalid weapon: '+w['id'])
for e in catalog['enemies']:
 if not(e['hp']>0 and e['damage']>0 and e['armor']>=0 and e['range']>0 and e['move']>=0):raise SystemExit('Invalid enemy: '+e['id'])
for m in catalog['mods']:
 if not(m['slot'] in [0,1] and 0<=m['stat']<=7 and m['value']>0 and 0<=m['unlock']<=3):raise SystemExit('Invalid modifier: '+m['id'])
for r in catalog['rooms']:
 if not(0<=r['theme']<=2 and 0<=r['layout']<=5):raise SystemExit('Invalid room: '+r['id'])
if '--validate' in sys.argv:print('Catalog is valid');sys.exit(0)
types={'weapons':'Weapon','mods':'Mod','enemies':'EnemyDef','artifacts':'Artifact','events':'EventDef','echoes':'Echo','rooms':'Room','roles':'Role','supplies':'Supply'}
def literal(v):
 if isinstance(v,str):return json.dumps(v,ensure_ascii=False).replace('$','\\$')
 if isinstance(v,bool):return str(v).lower()
 return str(v)
lines=['package com.riftwardechoprotocol.k7m4x9.core','','// Generated by Tools/generate_catalog.py from content/catalog.json.','object Content {']
for name,value in catalog.items():
 if name in types:
  lines.append(f'    val {name} = listOf(')
  for row in value:lines.append('        '+types[name]+'('+', '.join(k+' = '+literal(v) for k,v in row.items())+'),')
  lines.append('    )')
 elif isinstance(value,list):lines.append('    val '+name+' = listOf('+', '.join(literal(x) for x in value)+')')
lines+=['}','']
dest=root/'app/src/main/java/com/riftwardechoprotocol/k7m4x9/core/Content.kt';text='\n'.join(lines)
if '--check' in sys.argv:
 if dest.read_text()!=text:raise SystemExit('Catalog changed: run Tools/generate_catalog.py')
 print('Kotlin catalog matches authored JSON')
else:dest.write_text(text);print('Generated Kotlin catalog')
